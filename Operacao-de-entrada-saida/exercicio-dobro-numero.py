# Faça um programa que peça numero ao input
# E mostre o dobro desse numero

# Entrada de dados
idade = int(input("Digite idade atual: "))
tempo = int(input("Digite quantos anos futuros: "))

# Processo computacional
dobro = idade * 2
futuro = idade + tempo

# Saida de  informações
print(f"Sua idade é: {idade} anos")
print(f"O dobro da sua idade é: {dobro} anos")
print(f"Daqui {tempo} anos você terá: {futuro} anos")